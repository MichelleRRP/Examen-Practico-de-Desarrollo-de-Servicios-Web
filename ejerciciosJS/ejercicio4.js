
// Crear un arreglo de números desordenados
let numeros = [15, 3, 9, 5, 12, 7, 1, 20, 8];

// Ordenar el arreglo de menor a mayor utilizando el método sort()
numeros.sort(function(a, b) {
    return a - b; // Si a < b, el resultado será negativo y el orden se mantendrá.
});

// Mostrar el arreglo ordenado
console.log("Arreglo ordenado de menor a mayor:", numeros);


